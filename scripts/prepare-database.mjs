import { readdir, readFile, mkdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = fileURLToPath(new URL('../', import.meta.url));
const directory = path.join(root, 'supabase/migrations');
const files = (await readdir(directory)).filter(name => name.endsWith('.sql')).sort();
const sections = await Promise.all(files.map(async name =>
  `-- ${name}\n${await readFile(path.join(directory, name), 'utf8')}`));
await mkdir(path.join(root, 'migration'), { recursive: true });
await writeFile(path.join(root, 'migration/01-schema.sql'),
  '-- Generated by npm run migration:prepare. Run ONCE on an EMPTY Supabase project.\n'
  + '-- For this SQL Editor route, do not also run supabase db push.\nBEGIN;\n'
  + sections.join('\n\n') + '\nCOMMIT;\n');
console.log('Prepared migration/01-schema.sql from ' + files.length + ' migrations.');
